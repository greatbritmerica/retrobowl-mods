#!/usr/bin/env python3
"""Name tables for play scripts, from the clean 1.6.49 binary:
   src/script_names.inc  - every game variable (slot record) and routine (gml_Script_*) by name, sorted
   site/names.js         - the same names for the Workshop's reference
Usage: gen_names.py <RetroBowl binary>"""
import sys, os, re, struct, json
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, '/home/claude/tools')
from macho import MachO
m = MachO(sys.argv[1]); d = m.data
IMAGE = 0x100000000
def cstr(va):
    o = m.va2off(va)
    if o is None: return None
    e = d.find(b'\0', o, o + 80)
    if e < 0: return None
    try: s = d[o:e].decode()
    except Exception: return None
    return s if re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', s) else None
# variable slot records: {char *name; int id;} - the name pointer sits 8 bytes before the id
vars = {}
for va in range(0x100f9f000, 0x100fb4000, 8):
    o = m.va2off(va)
    if o is None: continue
    p = m.decode_ptr(struct.unpack_from('<Q', d, o - 8)[0])
    if not p: continue
    s = cstr(p)
    if s and not s.startswith('__') and s not in vars: vars[s] = va
assert vars.get('down') == 0x100fa4b48 and vars.get('x') == 0x100fb07e8, 'slot table moved'
names = json.load(open('/home/claude/tools/names.json'))
scripts = {}
for k, v in names.items():
    if str(v).startswith('gml_Script_') and 0x100020000 < int(k, 16) < 0x100e00000: scripts.setdefault(v[len('gml_Script_'):], int(k, 16))
assert scripts.get('s_spike_ball') == 0x1005760bc
V = sorted(vars.items()); S = sorted(scripts.items())
out = ['// GENERATED by tools/gen_names.py from the 1.6.49 binary. Do not edit.',
       'typedef struct { const char *n; unsigned off; } NameVA;   // off = address - 0x100000000',
       'static const NameVA RB_VARS[] = {'] + ['    { "%s", 0x%x },' % (n, va - IMAGE) for n, va in V] + ['};',
       'static const NameVA RB_SCRIPTS[] = {'] + ['    { "%s", 0x%x },' % (n, va - IMAGE) for n, va in S] + ['};', '']
open(os.path.join(root, 'src', 'script_names.inc'), 'w').write('\n'.join(out))
open(os.path.join(root, 'site', 'names.js'), 'w').write(
    '// GENERATED by tools/gen_names.py\n(function(r){var N={vars:%s,routines:%s};if(typeof module!=="undefined")module.exports=N;else r.WS_NAMES=N;})(typeof window!=="undefined"?window:this);\n'
    % (json.dumps([n for n, _ in V], separators=(',', ':')), json.dumps([n for n, _ in S], separators=(',', ':'))))
print(len(V), 'variables,', len(S), 'routines')
