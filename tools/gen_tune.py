#!/usr/bin/env python3
"""Regenerate src/tune.h and src/tune_table.inc from tools/tunables.json (the website embeds the same file)."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = json.load(open(os.path.join(root, 'tools', 'tunables.json')))
keys = [t['key'] for t in T]
assert len(keys) == len(set(keys))
h = ['// tune.h - GENERATED by tools/gen_tune.py from tools/tunables.json. Do not edit.', '#pragma once', 'typedef enum {']
h += ['    T_%s,' % k.upper() for k in keys] + ['    T_COUNT', '} TuneId;', '',
      'typedef struct { const char *key; double def, min, max; } TuneDef;', 'extern const TuneDef RB_TUNE[T_COUNT];', '',
      'double T(TuneId id);                              // the value in force right now (settings file, then rules)',
      'void rb_tune_load(void);                          // re-read Documents/rbmod_settings.txt (cheap; call once per play)',
      'void rb_tune_play_reset(void);                    // drop the "this play only" changes rules made',
      'int  rb_tune_find(const char *key);               // id, or -1',
      "void rb_tune_apply(int id, char op, double v, int keep);   // op: '=' '+' '*'; keep=1 until the app restarts or the file changes", '']
open(os.path.join(root, 'src', 'tune.h'), 'w').write('\n'.join(h))
c = ['// GENERATED by tools/gen_tune.py from tools/tunables.json. Do not edit.', 'const TuneDef RB_TUNE[T_COUNT] = {']
c += ['    { "%s", %r, %r, %r },' % (t['key'], float(t['def']), float(t['min']), float(t['max'])) for t in T] + ['};', '']
open(os.path.join(root, 'src', 'tune_table.inc'), 'w').write('\n'.join(c))
print(len(T), 'tunables')
